type baseConfig struct {
	Timeout string `toml:"timeout" default:"10s" doc:"Request timeout"`
}

// sampleConfig uses every feature of the configuration struct that the
// decoder understands.
type sampleConfig struct {
	Token  string `toml:"token" required:"true" doc:"API token"`
	Region string
	Secret string     `toml:"-"`
	hidden string     //nolint:unused // exercises the skipping of unexported fields
	Addr   netip.Addr `toml:"addr" doc:"A leaf struct is one parameter, not a table"`
	Auth   struct {
		User string `toml:"user" required:"true" doc:"Login"`
	} `toml:"auth"`
	Extra *struct {
		Key string `toml:"key" required:"true" doc:"Key of the optional block"`
	} `toml:"extra"`

	baseConfig
}

func TestDescribeCoversEveryKindOfField(t *testing.T) {
	params, err := describe(reflect.TypeFor[sampleConfig]())
	if err != nil {
		t.Fatal(err)
	}

	str, addr := reflect.TypeFor[string](), reflect.TypeFor[netip.Addr]()

	want := []param{
		{name: "token", required: true, doc: "API token", typ: str},
		{name: "region", typ: str},
		{name: "addr", doc: "A leaf struct is one parameter, not a table", typ: addr},
		{name: "auth.user", required: true, doc: "Login", typ: str},
		{name: "extra.key", required: true, doc: "Key of the optional block", typ: str, optionalTable: "extra"},
		{name: "timeout", defaultVal: "10s", hasDefault: true, doc: "Request timeout", typ: str},
	}

	if !reflect.DeepEqual(params, want) {
		t.Errorf("describe:\n got %+v\nwant %+v", params, want)
	}
}

// The documentation is only worth having if it names the parameters the
// decoder accepts and demands, so the two are checked against each other.
func TestDescribeAgreesWithDecode(t *testing.T) {
	params, err := describe(reflect.TypeFor[sampleConfig]())
	if err != nil {
		t.Fatal(err)
	}

	for _, p := range params {
		_, err := plugin.Decode[sampleConfig](nestedParams(p.name))
		if err != nil && strings.Contains(err.Error(), "unknown parameter") {
			t.Errorf("documented parameter %q is unknown to Decode: %v", p.name, err)
		}
	}

	// The decoder reports the required parameters of a nested table only once
	// the top-level ones are satisfied, hence two rounds.
	given := map[string]any{}
	for _, p := range params {
		if p.required && !strings.Contains(p.name, ".") {
			given[p.name] = "x"
		}
	}

	rounds := []struct {
		name   string
		given  map[string]any
		nested bool
	}{
		{"top level", map[string]any{}, false},
		{"nested", given, true},
	}

	for _, round := range rounds {
		_, err := plugin.Decode[sampleConfig](round.given)
		if err == nil {
			t.Fatalf("%s: Decode accepted the configuration although some parameters are required", round.name)
		}

		for _, p := range params {
			if strings.Contains(p.name, ".") != round.nested {
				continue
			}

			reported := strings.Contains(err.Error(), fmt.Sprintf("%q is required", p.name))
			mustBe := p.required && p.optionalTable == ""

			if reported != mustBe {
				t.Errorf("%s: parameter %q: Decode reports it missing = %v, documentation says required = %v",
					round.name, p.name, reported, mustBe)
			}
		}
	}
}

// nestedParams builds the raw parameters that set one dotted name.
func nestedParams(name string) map[string]any {
	head, tail, nested := strings.Cut(name, ".")
	if !nested {
		return map[string]any{head: "x"}
	}

	return map[string]any{head: nestedParams(tail)}
}

func TestDescribeRejectsAmbiguousConfigurations(t *testing.T) {
	type duplicate struct {
		A string `toml:"name"`
		B string `toml:"NAME"`
	}

	tests := map[string]reflect.Type{
		"duplicate name": reflect.TypeFor[duplicate](),
		"not a struct":   reflect.TypeFor[string](),
	}

	for name, typ := range tests {
		t.Run(name, func(t *testing.T) {
			if _, err := describe(typ); err == nil {
				t.Error("describe accepted the type")
			}
		})
	}
}

