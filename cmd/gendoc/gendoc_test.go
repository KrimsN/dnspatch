func TestRenderMarksRequiredParametersOfOptionalTables(t *testing.T) {
	type config struct {
		Extra *struct {
			Key string `toml:"key" required:"true" doc:"Key"`
		} `toml:"extra"`
	}

	got, err := render(nil, map[string]reflect.Type{"p": reflect.TypeFor[config]()})
	if err != nil {
		t.Fatal(err)
	}

	if want := "| `extra.key` | if `extra` is set | — | Key |"; !strings.Contains(string(got), want) {
		t.Errorf("no row %q in:\n%s", want, got)
	}
}

