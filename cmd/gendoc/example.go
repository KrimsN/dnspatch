package main

import (
	"fmt"
	"reflect"
	"regexp"
	"strconv"
	"strings"
	"time"
	"unicode"

	"github.com/KrimsN/dnspatch/internal/config"
	"github.com/KrimsN/dnspatch/internal/paramspec"
)

const (
	// placeholder stands in for a required string that has no `example` tag.
	// It is meant to be noticed and replaced.
	placeholder = "CHANGE_ME"

	commentWidth = 78
)

var (
	bareKey      = regexp.MustCompile(`^[A-Za-z0-9_-]+$`)
	durationType = reflect.TypeFor[time.Duration]()
)

// renderExample builds a configuration file to copy and edit: a definition of
// every plugin with its required parameters filled with placeholders, its
// optional ones commented out with their defaults, and one instance that ties
// the first retriever to the first provider.
func renderExample(retrievers, providers map[string]reflect.Type) ([]byte, error) {
	var b strings.Builder

	b.WriteString("# Code generated by cmd/gendoc; DO NOT EDIT.\n")
	b.WriteString("#\n")
	b.WriteString("# dnspatch example configuration. Copy it to dnspatch.toml, replace the\n")
	b.WriteString("# placeholders, and delete the definitions you do not use.\n")
	b.WriteString("#\n")
	b.WriteString("# Uncommented parameters are required. A commented parameter is optional and\n")
	b.WriteString("# shows its default; uncomment it to change it. Every parameter is described in\n")
	b.WriteString("# docs/PARAMETERS.md. A value such as ${NAME} is read from the environment.\n")
	b.WriteString("#\n")
	b.WriteString("# This file is generated from plugin struct tags, so manual edits are\n")
	b.WriteString("# overwritten. After changing a plugin configuration, run `go generate ./...`.\n\n")

	b.WriteString("# How often instances check the address. An instance can set its own.\n")
	fmt.Fprintf(&b, "interval = %s\n\n", tomlString(shortDuration(config.DefaultInterval)))

	retrieverNames, providerNames := sortedNames(retrievers), sortedNames(providers)

	if err := writeDefinitions(&b, "retriever", "Retrievers: where the current address comes from.", retrievers, retrieverNames); err != nil {
		return nil, err
	}

	if err := writeDefinitions(&b, "provider", "Providers: where the address is published.", providers, providerNames); err != nil {
		return nil, err
	}

	writeInstance(&b, retrieverNames, providerNames)

	return []byte(strings.TrimRight(b.String(), "\n") + "\n"), nil
}

// writeDefinitions writes one [<kind>.<name>] table per plugin.
func writeDefinitions(b *strings.Builder, kind, title string, plugins map[string]reflect.Type, names []string) error {
	writeBanner(b, title)

	for _, name := range names {
		if !bareKey.MatchString(name) {
			return fmt.Errorf("%s %q: the name cannot be used as a bare TOML key", kind, name)
		}

		params, err := describe(plugins[name])
		if err != nil {
			return fmt.Errorf("%s %q: %w", kind, name, err)
		}

		fmt.Fprintf(b, "[%s.%s]\ntype = %s\n\n", kind, name, tomlString(name))

		for _, p := range params {
			if err := writeParam(b, p); err != nil {
				return fmt.Errorf("%s %q: %w", kind, name, err)
			}
		}
	}

	return nil
}

// writeParam writes one parameter with the first sentence of its description.
// A required parameter is left active, and an optional one is commented out.
func writeParam(b *strings.Builder, p param) error {
	if !bareKey.MatchString(strings.ReplaceAll(p.name, ".", "-")) {
		return fmt.Errorf("parameter %q cannot be written as a bare TOML key", p.name)
	}

	// The parameters of an optional table are only used once the table is
	// written, so they stay commented out even when required.
	active := p.required && p.optionalTable == ""

	value, err := exampleValue(p)
	if err != nil {
		return fmt.Errorf("parameter %q: %w", p.name, err)
	}

	text := summary(p.doc)
	if p.required && p.optionalTable != "" {
		text = strings.TrimSpace(text + " Required once " + p.optionalTable + " is set.")
	}

	for _, line := range wrap(text, commentWidth-2) {
		b.WriteString("# " + line + "\n")
	}

	prefix := "# "
	if active {
		prefix = ""
	}
	fmt.Fprintf(b, "%s%s = %s\n\n", prefix, p.name, value)

	return nil
}

// exampleValue picks the value shown for a parameter. A required parameter
// shows its example or a placeholder, since it has to be edited anyway; an
// optional one shows its default, so that uncommenting it changes nothing
// until the reader edits it, and falls back to the example or the zero value.
func exampleValue(p param) (string, error) {
	switch {
	case p.required && p.hasExample:
		return literal(p.typ, p.example)
	case p.hasDefault:
		return literal(p.typ, p.defaultVal)
	case p.hasExample:
		return literal(p.typ, p.example)
	case p.required && isPlainString(p.typ):
		return tomlString(placeholder), nil
	case p.required:
		return "", fmt.Errorf("a required parameter of type %s needs an example tag", p.typ)
	default:
		return zeroLiteral(p.typ)
	}
}

// writeInstance writes an instance using the first retriever and provider.
func writeInstance(b *strings.Builder, retrieverNames, providerNames []string) {
	writeBanner(b, "Instances: each one ties a retriever to the providers it updates.")

	if len(retrieverNames) == 0 || len(providerNames) == 0 {
		b.WriteString("# No retriever or no provider is registered, so there is no instance to show.\n")
		return
	}

	b.WriteString("# Add more [[instance.provider]] tables to update several providers. Parameters\n")
	b.WriteString("# set next to a ref override the definition, for example another zone.\n")
	b.WriteString("[[instance]]\n")
	b.WriteString("name = \"home\"\n\n")
	fmt.Fprintf(b, "[instance.retriever]\nref = %s\n\n", tomlString(retrieverNames[0]))
	fmt.Fprintf(b, "[[instance.provider]]\nref = %s\n", tomlString(providerNames[0]))
}

func writeBanner(b *strings.Builder, title string) {
	rule := "# " + strings.Repeat("-", commentWidth-2) + "\n"

	b.WriteString(rule)
	b.WriteString("# " + title + "\n")
	b.WriteString(rule)
	b.WriteString("\n")
}

// literal renders a tag value as a TOML value of the parameter's type. Slices
// and maps take the tag value as TOML text, since there is no better way to
// write one in a tag.
func literal(t reflect.Type, raw string) (string, error) {
	if t == durationType {
		if _, err := time.ParseDuration(raw); err != nil {
			return "", fmt.Errorf("%q is not a duration", raw)
		}

		return tomlString(raw), nil
	}

	if isText(t) {
		return tomlString(raw), nil
	}

	switch t.Kind() {
	case reflect.Bool:
		v, err := strconv.ParseBool(raw)
		if err != nil {
			return "", fmt.Errorf("%q is not a boolean", raw)
		}

		return strconv.FormatBool(v), nil
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64:
		v, err := strconv.ParseInt(raw, 10, 64)
		if err != nil {
			return "", fmt.Errorf("%q is not an integer", raw)
		}

		return strconv.FormatInt(v, 10), nil
	case reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64:
		v, err := strconv.ParseUint(raw, 10, 64)
		if err != nil {
			return "", fmt.Errorf("%q is not a non-negative integer", raw)
		}

		return strconv.FormatUint(v, 10), nil
	case reflect.Float32, reflect.Float64:
		v, err := strconv.ParseFloat(raw, 64)
		if err != nil {
			return "", fmt.Errorf("%q is not a number", raw)
		}

		text := strconv.FormatFloat(v, 'f', -1, 64)
		if !strings.Contains(text, ".") {
			text += ".0"
		}

		return text, nil
	case reflect.Slice, reflect.Map:
		return raw, nil
	default:
		return "", fmt.Errorf("type %s has no TOML form", t)
	}
}

// zeroLiteral renders the empty value of a type, for a commented-out
// parameter that has neither a default nor an example.
func zeroLiteral(t reflect.Type) (string, error) {
	switch {
	case t == durationType:
		return `"0s"`, nil
	case isText(t):
		return `""`, nil
	}

	switch t.Kind() {
	case reflect.Bool:
		return "false", nil
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
		reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64:
		return "0", nil
	case reflect.Float32, reflect.Float64:
		return "0.0", nil
	case reflect.Slice:
		return "[]", nil
	case reflect.Map:
		return "{}", nil
	default:
		return "", fmt.Errorf("type %s has no TOML form", t)
	}
}

// isText reports whether a type is written as a TOML string: a string, or a
// type such as netip.Addr that parses itself from text.
func isText(t reflect.Type) bool {
	return t.Kind() == reflect.String || paramspec.ParsesText(t)
}

// isPlainString reports whether a type is a string that takes any text, which
// is what makes a placeholder a sensible value for it.
func isPlainString(t reflect.Type) bool {
	return t.Kind() == reflect.String && t != durationType
}

// tomlString writes text as a TOML basic string.
func tomlString(text string) string {
	var b strings.Builder

	b.WriteByte('"')

	for _, r := range text {
		switch {
		case r == '"':
			b.WriteString(`\"`)
		case r == '\\':
			b.WriteString(`\\`)
		case r == '\n':
			b.WriteString(`\n`)
		case r == '\t':
			b.WriteString(`\t`)
		case r < 0x20 || r == 0x7f:
			fmt.Fprintf(&b, `\u%04X`, r)
		default:
			b.WriteRune(r)
		}
	}

	b.WriteByte('"')

	return b.String()
}

// shortDuration writes a duration the way a person would: 5m, not 5m0s.
func shortDuration(d time.Duration) string {
	text := d.String()

	if strings.HasSuffix(text, "m0s") {
		text = strings.TrimSuffix(text, "0s")
	}

	if strings.HasSuffix(text, "h0m") {
		text = strings.TrimSuffix(text, "0m")
	}

	return text
}

// summary returns the first sentence of a description, so that a template
// stays short and the full text stays in docs/PARAMETERS.md. A sentence ends at
// a period followed by a space and a capital letter.
func summary(doc string) string {
	doc = strings.Join(strings.Fields(doc), " ")

	for i := 0; i+2 < len(doc); i++ {
		if doc[i] == '.' && doc[i+1] == ' ' && unicode.IsUpper(rune(doc[i+2])) {
			return doc[:i+1]
		}
	}

	return doc
}

// wrap breaks text into lines of at most width characters, without splitting
// words.
func wrap(text string, width int) []string {
	var (
		lines []string
		line  string
	)

	for _, word := range strings.Fields(text) {
		switch {
		case line == "":
			line = word
		case len(line)+1+len(word) <= width:
			line += " " + word
		default:
			lines = append(lines, line)
			line = word
		}
	}

	if line != "" {
		lines = append(lines, line)
	}

	return lines
}
